#include <stdio.h>
#include <stdint.h>
#include "../../src/sensors/Ublox_SAM_M8Q/ubx_proto.h"

// example ubx packet.
uint8_t ubx_nav_pvt_sample[] = {
    0xB5, 0x62,             // Sync chars
    0x01, 0x07,             // Class = NAV, ID = PVT
    0x5C, 0x00,             // Payload length = 92 bytes

    // Payload (92 bytes)
    0xE4, 0x07, 0x08, 0x1A,  // iTOW = 0x1A08E4 (example)
    0x0C, 0x1E, 0x17, 0x05,  // year=2023, month=5, day=23, hour=30
    0x2A, 0x10,             // min=42, sec=16
    0x00,                   // valid
    0xA0, 0x86, 0x01, 0x00,  // tAcc
    0x20, 0x4E, 0x00, 0x00,  // nano
    0x03,                   // fixType (3 = 3D fix)
    0x01,                   // flags
    0x00,                   // flags2
    0x0C,                   // numSV = 12

    // Longitude, Latitude (1e-7 deg)
    0x15, 0xCD, 0x5B, 0x02,  // lon = 39.1234567°
    0xB2, 0x9E, 0x43, 0x01,  // lat = 20.6543210°

    // Height, hMSL (mm)
    0x10, 0x27, 0x00, 0x00,  // height
    0xF0, 0x26, 0x00, 0x00,  // hMSL

    // hAcc, vAcc (mm)
    0xE8, 0x03, 0x00, 0x00,
    0x10, 0x27, 0x00, 0x00,

    // velN, velE, velD (mm/s)
    0x00, 0x00, 0x00, 0x00,
    0x10, 0x00, 0x00, 0x00,
    0xF0, 0xFF, 0xFF, 0xFF,

    // gSpeed, headMot
    0x10, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00,

    // sAcc, headAcc
    0x64, 0x00, 0x00, 0x00,
    0x88, 0x13, 0x00, 0x00,

    // pDOP
    0x2C, 0x01,

    // reserved
    0x00, 0x00, 0x00, 0x00,
    0x00, 0x00,

    // headVeh
    0x00, 0x00, 0x00, 0x00,

    // magDec, magAcc
    0x00, 0x00,
    0x00, 0x00,

    // Checksum (CK_A, CK_B)
    0x4E, 0xA5
};


